import artistData from '../data/artists.json';
import decadeData from '../data/decades.json';
import worksData from '../data/works.json';
import topicData from '../data/topics.json';
import sourceData from '../data/sources.json';
import siteData from '../data/site.json';
import type { Artist, Decade, Work, Topic, Source } from '../types/content';
export const artists = artistData as Artist[];
export const decades = decadeData as Decade[];
export const works = worksData as Work[];
export const topics = topicData as Topic[];
export const sources = sourceData as Source[];
export const site = siteData;
export const getArtist = (id: string) => artists.find(a => a.id === id);
export const getArtistWorks = (artist: Artist) => works.filter(w => artist.workIds.includes(w.id));
export const normalize = (text: string) => text.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
